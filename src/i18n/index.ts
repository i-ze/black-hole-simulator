const DICTS: Record<Lang, Dict> = { hu, en };

export type TFn = (key: string, params?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let v: unknown = DICTS[lang];
  for (const k of key.split('.')) v = (v as Record<string, unknown> | undefined)?.[k];
  let s = typeof v === 'string' ? v : key;
  if (params) for (const [k, p] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(p));
  return s;
}

export function useT(): TFn {
  const lang = useUI((s) => s.lang);
  return (key, params) => translate(lang, key, params);
}
